const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const root=path.resolve(__dirname,".."),get=name=>fs.readFileSync(path.join(root,name),"utf8");
const files=["arcade.html","arcade.css","arcade-immersive.css","arcade-core.js","arcade-puzzles.js","arcade-action.js","arcade-party.js","arcade-init.js","site-theme.js"];
for(const file of files)assert.ok(fs.existsSync(path.join(root,file)),file+" exists");
const html=get("arcade.html"),index=get("index.html"),party=get("party.html");
assert.match(get("arcade-puzzles.js"),/boardEl\.addEventListener\("touchstart"/,"2048 tracks touch swipes on the board");
assert.match(get("arcade-puzzles.js"),/boardEl\.addEventListener\("touchend"/,"2048 turns swipes into moves");
assert.match(get("arcade-immersive.css"),/body\[data-game="2048"\] \.direction-pad,body\[data-game="snake"\] \.direction-pad \{display:none\}/,"direction pads are hidden on mobile for 2048 and Snake");
assert.match(get("arcade-action.js"),/c\.addEventListener\("pointerdown"/,"Snake joystick starts at the first touch position");
assert.match(get("arcade-action.js"),/c\.addEventListener\("pointerup"/,"Snake joystick resets when touch ends");
for(const file of files.filter(x=>x.endsWith(".js")&&x!=="site-theme.js"))assert.ok(html.includes('src="'+file+'"'),file+" loaded");
const expected=["typing","2048","wordle","mines","pong","snake","headsup","uno","ladders","combat"];
const handlers={};
const context={window:{Arcade:{register:(id,fn)=>handlers[id]=fn}},Math,Date,Array,Object,Number,String,Set,Map,JSON,RegExp,localStorage:{getItem:()=>null,setItem:()=>{}}};
vm.createContext(context);
vm.runInContext(get("arcade-puzzles.js"),context);
vm.runInContext(get("arcade-action.js"),context);
vm.runInContext(get("arcade-party.js"),context);
for(const id of expected)assert.equal(typeof handlers[id],"function","game registered "+id);
for(const id of ["typing","2048","wordle","mines"])assert.match(index,new RegExp('game='+id+'["]'),"home lists "+id);
for(const id of ["headsup","uno","ladders","snake","combat"])assert.ok(party.includes("game="+id),"party lists "+id);
assert.doesNotMatch(party,/id:'pong'|id:"pong"/,"Pong appears in the main catalog, not Party Space");
assert.doesNotMatch(html,/id="gameNav"|href="arcade.html">All games|class="grid-cards"/,"no arcade landing or sidebar");
assert.match(html,/class="game-stage"/,"dedicated playfield");
assert.match(html,/id="gameIntro"/,"game-specific intro menu");
assert.doesNotMatch(index,/<a href="\.\/arcade\.html"[^>]*>Arcade<\/a>/,"no standalone arcade link");
const homeDescriptions=[...index.matchAll(/\bdescription:\s*["']([^"']+)["']/g)].map(m=>m[1]);
const partyDescriptions=[...party.matchAll(/\bdesc:\s*["']([^"']+)["']/g)].map(m=>m[1]);
for(const desc of [...homeDescriptions,...partyDescriptions]) assert.ok(desc.trim().split(/\s+/).length<=3,"three-word description: "+desc);
assert.match(index,/id:"pong"[^}]*type:"solo"/,"Pong is classified in the main catalog");
for(const id of ["snake","combat"])assert.match(index,new RegExp('id:"'+id+'"[^}]*type:"party"'),id+" is classified under Party Space");
const {evaluate,daysRemaining,WORDS}=context.window.Arcade.wordle;
assert.equal(daysRemaining(new Date(2026,10,16)),45);
assert.equal(daysRemaining(new Date(2026,11,31)),0);
assert.equal(daysRemaining(new Date(2027,0,1)),364);
assert.equal(daysRemaining(new Date(2028,0,1)),365);
assert.equal(WORDS.filter(w=>w.length!==5).length,0,"answer list must contain only five-letter words");
assert.ok(new Set(WORDS).size >= 366,"enough distinct words for the full year");
const nextYear=Array.from({length:365},(_,day)=>WORDS[(day*173+2027*37)%WORDS.length]);
assert.equal(new Set(nextYear).size,365,"one unique answer per day of a non-leap year");
assert.equal(JSON.stringify([...evaluate("ALLEY","APPLE")]),JSON.stringify(["correct","present","absent","present","absent"]),"duplicate-letter feedback");
const catalogText=get("offline-catalog.js"),serviceWorker=get("sw.js");
for(const id of expected)assert.ok(catalogText.includes('"'+id+'"'),"offline catalog contains "+id);
assert.match(serviceWorker,/arcade\.html/,"service worker pre-caches arcade");
assert.match(index,/name="description"/);
assert.match(index,/property="og:title"/);
console.log("PASS: Arcade pages, ten game registrations, both catalogs, Wordle dates/scoring, SEO and offline setup");
